-- Ghar Ka Zayeka menu table and safe access policies
-- Run this in Supabase Dashboard > SQL Editor.
create table if not exists public.menu_items (
  id bigint generated by default as identity primary key,
  name text not null,
  price numeric(10,2) not null check (price >= 0),
  image_url text,
  description text,
  is_available boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.menu_items add column if not exists category text;
alter table public.menu_items enable row level security;
grant select on public.menu_items to anon, authenticated;
grant insert, update, delete on public.menu_items to authenticated;
grant usage, select on sequence public.menu_items_id_seq to authenticated;

drop policy if exists "Anyone can view available menu items" on public.menu_items;
create policy "Anyone can view available menu items"
on public.menu_items for select
to anon, authenticated
using (is_available = true or auth.jwt() ->> 'email' = 'cbsedivdeepak2007@gmail.com');

drop policy if exists "Admin can add menu items" on public.menu_items;
create policy "Admin can add menu items"
on public.menu_items for insert
to authenticated
with check (auth.jwt() ->> 'email' = 'cbsedivdeepak2007@gmail.com');

drop policy if exists "Admin can update menu items" on public.menu_items;
create policy "Admin can update menu items"
on public.menu_items for update
to authenticated
using (auth.jwt() ->> 'email' = 'cbsedivdeepak2007@gmail.com')
with check (auth.jwt() ->> 'email' = 'cbsedivdeepak2007@gmail.com');

drop policy if exists "Admin can delete menu items" on public.menu_items;
create policy "Admin can delete menu items"
on public.menu_items for delete
to authenticated
using (auth.jwt() ->> 'email' = 'cbsedivdeepak2007@gmail.com');
